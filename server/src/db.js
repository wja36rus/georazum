/* Детерминированная оценка расстояния между двумя несмежными участками. */
function distanceBetween(a, b) {
  const direct = DISTANCE_M[a] && DISTANCE_M[a][b];
  if (direct) return direct;
  let h = 0;
  const s = a + b;
  for (let i = 0; i < s.length; i++) {
    h = (h * 31 + s.charCodeAt(i)) >>> 0;
  }
  return 900 + (h % 4100);
}

