/* Пароль: scrypt из стандартной библиотеки (мок, но осмысленный) */
function hash(password) {
  const salt = crypto.randomBytes(8).toString("hex");
  return (
    salt + ":" + crypto.scryptSync(String(password), salt, 32).toString("hex")
  );
}
function verify(password, stored) {
  if (!stored) return false;
  const [salt, hex] = stored.split(":");
  if (!salt || !hex) return false;
  const check = crypto.scryptSync(String(password), salt, 32).toString("hex");
  return crypto.timingSafeEqual(
    Buffer.from(hex, "hex"),
    Buffer.from(check, "hex"),
  );
}

